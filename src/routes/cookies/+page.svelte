  <h3>1. What Are Cookies?</h3>
  <p>Cookies are small text files placed on your device by a website. They allow the website to recognize your device, store preferences, and improve user experience. Cookies may be "first-party" (set by our website) or "third-party" (set by external services).</p>

  <hr />

  <h3>2. Types of Cookies We Use</h3>

  <h4>Essential Cookies</h4>
  <p>These cookies are necessary for the proper functioning of our website and cannot be turned off. They include:</p>
  <ul>
    <li><strong>Theme & Appearance</strong>: Remembering your theme (light/dark), background (enabled/disabled), and whether the download button is shown.</li>
    <li><strong>Navigation & Tabs</strong>: Remembering your active tab and last visited page.</li>
    <li><strong>PDF Reader (Oread)</strong>: Saving your current page, last 5 PDFs, reading modes (Paper, Night, E-Ink), and scheduled reading preferences.</li>
    <li><strong>Authentication</strong>: required for login and secure access.</li>
    <li><strong>Privileges</strong>: Checking if you have admin privileges, Plus benefits, or none.</li>
    <li><strong>Notifications</strong>: Tracking read/unread notifications so you don't see duplicates.</li>
    <li><strong>Insightroom Access</strong>: Remembering whether private posts should be shown (based on admin/Plus status).</li>
  </ul>

  <h4>Performance and Analytics Cookies</h4>
  <p>We use these to analyze how visitors use our website and improve user experience. Examples include:</p>
  <ul>
    <li><strong>Google Analytics 4 (GA4):</strong> Tracks site performance, engagement, and traffic.</li>
    <li><strong>Engagement Tracking:</strong> Time spent on PDFs, active sessions, and navigation flow.</li>
    <li><strong>AI Summary:</strong> Determines whether you have necessary perks to show AI summary or not.</li>
  </ul>

  <h4>Functional Cookies</h4>
  <p>These cookies enhance site functionality and user choice, such as:</p>
  <ul>
    <li>Showing or hiding promotions.</li>
    <li>Showing or hiding the PWA app installation popup.</li>
    <li>Enabling Giscus comments on PDFs and posts.</li>
  </ul>

