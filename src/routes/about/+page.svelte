  <h3>So, What is Materio?</h3>
  <p>Materio - A study SaaS that simplifies your CS preparation with verified, crowd-curated notes and fast access to semester-specific resources.</p>
  <ul>
    <li>It is a place where you can find all the study materials organised and categorized based on semesters, subjects, categories, and topics (aka chapters).</li>
    <li>All you need to do is select all the four options in the dropdown menus and click "Start Reading" and it will open your selected PDF in the PopUp modal window.</li>
  </ul>

  <h3>Why Tho?</h3>
  <ul>
    <li>So, the objective is clear - Eliminate the time wastage finding the proper PDF you need, Especially when the exams are near and time's running out and you're out here scrolling through n number of WhatsApp Study groups, class groups, all kinds of Google Drive links, and when after going through all these effort you still don't find what you're looking for?</li>
    <li>Second objective was to eliminate the need of downloading all the PDFs which at some point fills out lot of storage, So Materio allows reading all the materials online itself.</li>
    <li>Materio is the place for you, as all the materials here are curated from official sources and most popular sources across the university.</li>
  </ul>

  <h3>I don't Find what i need here too, what to do now?</h3>
  <ul>
    <li>Thats what the chat feature is for, Request the specific material you need or share if you have something new with the community. Ask doubts, Solve together, Help Each other.</li>
    <li>Your Requested Material will be there on the site within 24 Hours.</li>
  </ul>

  <h2>I appreciate Online only approach but i still want to be able to download PDFs, My internet isn't good.</h2>
  <ul>
    <li>I have a good news for you then, Materio now supports offline reading capabilities too, Just get the Webapp (PWA) when prompted to install the website will work too if you don't want to download the webapp.</li>
    <li>When you open any PDF when online you can find a bookmark icon with + mark in it, Simply click it and your PDF will be ready for offline reading.</li>
    <li>Access it by clicking the profile icon (in the navbar) -> Downloads, You will find all the PDF's that you have downloaded here. Click Open and PDF will load without an active internet connection.</li>
  </ul>

  <h3>But i want files to Download in my PC</h3>
  <ul>
    <li>Yeah, this feature is kept exclusive for our Plus tier users.</li>
    <li>How to Get Plus you may ask?
      <ul>
        <li>Plus is currently invite only, you can join the waitlist by mailing to our support and request for access. You'll be provided with your code to redeem your Plus benefits.</li>
        <li>Plus contains additional benefits like AI Summary in Posts, Ad-free Experience, early preview's or Beta updates before everyone else gets them along with ability to Download PDFs.</li>
      </ul>
    </li>
  </ul>

  <h2>Features</h2>
  <ul>
    <li>Organized Materials by Semester, Subject, Category and Topics.</li>
    <li>Chat - To help, discuss or request/contribute materials.</li>
    <li>Notifications - Get notified whenever new materials are uploaded.</li>
    <li>Finder / AI Search - Find Materials by typing keywords, Use AI mode to get more optimized solutions or Get random suggestions to read.</li>
    <li>Reading Mode's - Personalize your reading experience with Paper, Night and E-ink overlay filters.</li>
    <li>The Insightroom - Find posts, assignment solutions, tips & tricks, PYQ Solutions, Cheatsheets, Notes etc with ability to convert to printable ebook or share links.</li>
    <li>Insightroom feed / Smart recommendations - Get latest posts served directly on your homepage or Smartly sorted suggested posts related to selected subject.</li>
    <li>Downloads - Bookmark PDFs to access offline</li>
    <li>Contributions - Submit missing or new resources and help make materio's resource library better.</li>
    <li>Tailored Experience for everyone - Customize your materio experience with Dark or Light mode themes, Change Background images or turn it off, Toggle insightroom feed on or off for Minimal experience.</li>
  </ul>

